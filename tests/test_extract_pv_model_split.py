def test_numbered_loop_trio_folds_into_entry_node():
    body = (
        "/-- [demo::f]: loop body 0:\n    Source: 'src/lib.rs', lines 1:0-2:0 -/\n"
        "@[rust_loop_body]\n"
        "def f_loop0.body (x : Std.U64) : Result Std.U64 := do\n  ok x\n\n"
        "/-- [demo::f]: loop 0:\n    Source: 'src/lib.rs', lines 1:0-2:0 -/\n"
        "@[rust_loop]\n"
        "def f_loop0 (x : Std.U64) : Result Std.U64 := do\n"
        "  loop (fun x1 => f_loop0.body x1) x\n\n"
        "/-- [demo::f]: loop body 1:\n    Source: 'src/lib.rs', lines 3:0-4:0 -/\n"
        "@[rust_loop_body]\n"
        "def f_loop1.body (x : Std.U64) : Result Std.U64 := do\n  ok x\n\n"
        "/-- [demo::f]: loop 1:\n    Source: 'src/lib.rs', lines 3:0-4:0 -/\n"
        "@[rust_loop]\n"
        "def f_loop1 (x : Std.U64) : Result Std.U64 := do\n"
        "  loop (fun x1 => f_loop1.body x1) x\n\n"
        "/-- [demo::f]:\n    Source: 'src/lib.rs', lines 1:0-4:0 -/\n"
        "def f (x : Std.U64) : Result Std.U64 := do\n"
        "  let x1 ← f_loop0 x\n  f_loop1 x1\n"
    )
    res = E.split_generated_lean(_wrap(body))
    # All five decls (2 loops, 2 bodies, the entry) collapse into ONE node `f`.
    assert [n.name for n in res.nodes] == ["f"], [n.name for n in res.nodes]
    region = res.nodes[0].region
    for decl in ("f_loop0.body", "f_loop0", "f_loop1.body", "f_loop1", "def f "):
        assert decl in region


