def test_boundary_axiom_routes_to_preamble_verbatim_and_stays_opaque():
    axiom_block = (
        "/-- [core::slice::{[T]}::first]:\n    Source: 'x', lines 1:1-1:2 -/\n"
        '@[rust_fun "core::slice::{[@T]}::first"]\n'
        "axiom core.slice.Slice.first {T : Type} : Slice T → Result (Option T)"
    )
    body = (
        f"{axiom_block}\n\n"
        "/-- [demo::g]\n    Source: 'src/lib.rs', lines 9:0-9:9 -/\n"
        "def g (x : Std.U64) : Result Std.U64 := do\n  core.slice.Slice.first x\n"
    )
    res = E.split_generated_lean(_wrap(body))
    assert [n.name for n in res.nodes] == ["g"]
    # External declarations are evidence, not an invitation for the extractor
    # to invent executable behavior: the complete Aeneas block is unchanged.
    assert axiom_block in res.preamble_text
    assert "def core.slice.Slice.first" not in res.preamble_text
    assert [item.name for item in res.boundary_axioms] == ["core.slice.Slice.first"]
    assert res.boundary_axioms[0].stubs == (
        "{T : Type} : Slice T → Result (Option T)"
    )
    assert "namespace demo" in res.preamble_text
    # the dependent node does NOT manufacture an import for a preamble axiom.
    assert res.nodes[0].deps == []


