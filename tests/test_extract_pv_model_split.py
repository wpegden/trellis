"""Unit tests for the pure-text FILESPEC splitter in `scripts/extract_pv_model.py`.

These exercise `split_generated_lean` over the aeneas output SHAPE CLASSES that
the richer PV targets (dec2flt and beyond) introduce over the montgomery spike:

  * loop trios — `f_loop<N>` / `f_loop<N>.body` (NUMBERED, and nested
    `f_loop<N>_loop<M>`) — fold into the ONE entry-point node `f`;
  * boundary `axiom`s (no `:=`/`by`/`where` body) route to the Preamble;
  * `structure`/`inductive` type definitions route to the Preamble (the import
    root) so derived boundary axioms over the type resolve;
  * a `noncomputable section` header is re-emitted in every node header.

Pure text — no charon/aeneas/lake. The end-to-end `--gate` (determinism +
`validate_filespec` + `prescribed_region` against the real kernel binaries) is the
operator-run regression; this file locks the shaping decisions in CI-fast form.
"""
import importlib.util
import hashlib
import json
import os
import pathlib
import sys

import pytest

_ROOT = pathlib.Path(__file__).resolve().parent.parent
_SPEC = importlib.util.spec_from_file_location(
    "extract_pv_model", _ROOT / "scripts" / "extract_pv_model.py"
)
E = importlib.util.module_from_spec(_SPEC)
# Register before exec so the module's `@dataclass(field(default_factory=...))`
# definitions can resolve their own module via `sys.modules` (py3.12+ dataclasses).
sys.modules["extract_pv_model"] = E
_SPEC.loader.exec_module(E)


_HEADER = (
    "-- THIS FILE WAS AUTOMATICALLY GENERATED BY AENEAS\n"
    "-- [demo]\n"
    "import Aeneas\n"
    "open Aeneas Aeneas.Std Result ControlFlow Error\n"
    "set_option linter.dupNamespace false\n"
)


def _wrap(body: str, *, noncomputable: bool = False) -> str:
    head = _HEADER
    if noncomputable:
        head += "noncomputable section\n"
    return f"{head}\nnamespace demo\n\n{body}\nend demo\n"


def test_multiline_declarations_share_identity_with_inventory(tmp_path):
    from trellis.modeling.modules import declaration_index
    raw = _wrap(
        "/-- [demo::Word]\n def bogus := 0\n -/\nstructure\n Word where\n value : Nat\n\n"
        "/-- [core::read] -/\naxiom\n read : Word → Nat\n\n"
        "/-- [demo::operation] -/\n@[irreducible]\nnoncomputable\ndef\n operation (w : Word) := read w\n\n"
        "/-- [demo::implementation] -/\nimpl_def\n Word.Insts.Reader := operation\n\n"
        "/-- [demo::consumer] -/\ndef consumer := Word.Insts.Reader\n"
    )
    (tmp_path / "M.lean").write_text(raw)
    split = E.split_generated_lean(raw)
    nodes = {node.name: node for node in split.nodes}
    assert set(nodes) == {"operation", "Word_Insts_Reader", "consumer"}
    assert nodes["consumer"].deps == ["Word_Insts_Reader"]
    assert nodes["Word_Insts_Reader"].deps == ["operation"]
    assert "def\n operation" in nodes["operation"].region
    index = {item["name"]: item for item in declaration_index(tmp_path)["declarations"]}
    assert set(index) == {"demo.Word", "demo.read", "demo.operation", "demo.Word.Insts.Reader", "demo.consumer"}
    assert raw.splitlines()[index["demo.operation"]["line"] - 1] == "@[irreducible]"


# ───────────── complete crate-source provenance ─────────────────


def _write_tree(root: pathlib.Path, files: list[tuple[str, bytes]]) -> None:
    for relative, raw in files:
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(raw)


def test_crate_source_hash_commits_complete_sorted_file_manifest(tmp_path):
    crate = tmp_path / "crate"
    # Deliberately create in reverse lexical order: filesystem enumeration must
    # not affect either the manifest or its digest.
    _write_tree(
        crate,
        [
            ("src/table.rs", b"pub const TABLE: u8 = 7;\n"),
            ("src/lib.rs", b"mod table;\n"),
            ("Cargo.toml", b"[package]\nname = \"demo\"\n"),
        ],
    )
    manifest = E.crate_source_tree_manifest(crate)
    expected_files = []
    for relative in ["Cargo.toml", "src/lib.rs", "src/table.rs"]:
        raw = (crate / relative).read_bytes()
        expected_files.append(
            {
                "relative_path": relative,
                "byte_length": len(raw),
                "sha256_of_raw_bytes": hashlib.sha256(raw).hexdigest(),
            }
        )
    expected_root = E.source_tree_root_from_entries(expected_files)
    expected = {
        "schema": E.CRATE_SOURCE_TREE_SCHEMA,
        "files": expected_files,
        "source_tree_sha256": expected_root,
    }
    assert manifest == expected
    assert E.crate_source_sha256(crate) == expected_root


def test_crate_source_hash_changes_for_non_lib_content_and_path(tmp_path):
    crate = tmp_path / "crate"
    _write_tree(
        crate,
        [
            ("Cargo.toml", b"[package]\nname = \"demo\"\n"),
            ("src/lib.rs", b"mod table;\n"),
            ("src/table.rs", b"pub const TABLE: u8 = 7;\n"),
        ],
    )
    original = E.crate_source_sha256(crate)
    (crate / "src/table.rs").write_bytes(b"pub const TABLE: u8 = 8;\n")
    changed_content = E.crate_source_sha256(crate)
    assert changed_content != original

    raw = (crate / "src/table.rs").read_bytes()
    (crate / "src/table.rs").unlink()
    (crate / "src/renamed.rs").write_bytes(raw)
    assert E.crate_source_sha256(crate) != changed_content


def test_source_snapshot_excludes_build_outputs_but_pins_every_exported_file(tmp_path):
    from trellis.modeling.observations import fingerprint
    crate = tmp_path / "input"
    _write_tree(crate, [("Cargo.toml", b'[package]\nname = "demo"\n'),
                        ("src/lib.rs", b"pub fn value() -> u8 { 7 }\n"),
                        ("target/debug/build-artifact", b"old build output"),
                        ("__pycache__/cache", b"cache")])
    snapshot = E.copy_crate_sources(crate, tmp_path / "export", selected_inputs=True)
    assert E.crate_source_tree_manifest(snapshot) == E.source_input_manifest(crate)
    assert fingerprint(snapshot) == fingerprint(crate)
    digest = E.crate_source_sha256(snapshot)
    (crate / "target/debug/build-artifact").write_bytes(b"new build output")
    assert fingerprint(snapshot) == fingerprint(crate)
    assert E.crate_source_sha256(E.copy_crate_sources(crate, tmp_path / "again", selected_inputs=True)) == digest
    (snapshot / "src/lib.rs").write_bytes(b"changed source")
    assert E.crate_source_sha256(snapshot) != digest


