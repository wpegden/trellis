def test_allowlist_replica_stays_in_lockstep_with_the_rust_constant() -> None:
    """D2 — the Python replica must equal `ISABELLE_HOL_ALLOWED_IMPORT_PREFIXES`.

    The replica gates the SESSION IMPORT ROOT. If it drifts wider than the Rust
    constant that gates worker imports, the root admits sessions the worker gate
    rejects; narrower, and a legal worker preamble silently falls back.
    """
    import re
    from pathlib import Path

    from trellis.checker.isabelle_scaffold import ALLOWED_PREAMBLE_IMPORT_PREFIXES

    backend_rs = (
        Path(__file__).resolve().parents[1] / "kernel" / "src" / "backend.rs"
    ).read_text(encoding="utf-8")
    block = re.search(
        r"ISABELLE_HOL_ALLOWED_IMPORT_PREFIXES:\s*&\[&str\]\s*=\s*&\[(.*?)\];",
        backend_rs,
        re.S,
    )
    assert block, "could not locate the Rust allowlist constant"
    rust = tuple(re.findall(r'"([^"]+)"', block.group(1)))
    assert tuple(ALLOWED_PREAMBLE_IMPORT_PREFIXES) == rust, (
        f"allowlist drift: python={tuple(ALLOWED_PREAMBLE_IMPORT_PREFIXES)} rust={rust}"
    )


def _derived_session(tmp_path, imports_line: str):
    """A session dir whose generated preamble is a DERIVED render."""
    from trellis.checker.isabelle_scaffold import sync_session

    (tmp_path / "Tablet").mkdir(parents=True, exist_ok=True)
    (tmp_path / "Tablet" / "Preamble.thy").write_text(
        f"theory Tablet_Preamble\n  imports {imports_line}\nbegin\n\nend\n",
        encoding="utf-8",
    )
    session = tmp_path / "isabelle"
    session.mkdir(exist_ok=True)
    sync_session(session)
    return session


def test_derived_preamble_is_sticky_against_a_failed_derivation(tmp_path) -> None:
    """D1 — a derivation failure must not silently narrow the import root.

    Once the session preamble is derived, falling back to `Complex_Main`
    re-elaborates every node in a different theory context: cert-cache keys mass-
    invalidate, and a node accepted in that window pins its approved corr
    fingerprint from narrow-env prints.
    """
    import pytest

    from trellis.checker.isabelle_scaffold import (
        DERIVED_PREAMBLE_MARKER,
        PREAMBLE_ALLOW_FALLBACK_ENV,
        sync_session,
    )

    session = _derived_session(tmp_path, '"HOL-Probability.Probability"')
    preamble = session / "Tablet_Preamble.thy"
    derived_bytes = preamble.read_bytes()
    assert DERIVED_PREAMBLE_MARKER in derived_bytes.decode()

    # Break the worker preamble (a torn read / bad edit).
    (tmp_path / "Tablet" / "Preamble.thy").write_text("garbage", encoding="utf-8")

    with pytest.raises(RuntimeError, match="DERIVED render"):
        sync_session(session)
    assert preamble.read_bytes() == derived_bytes, "derived bytes must survive"


def test_derived_preamble_fallback_override(tmp_path, monkeypatch) -> None:
    """D1 — the operator override forces the historical fallback."""
