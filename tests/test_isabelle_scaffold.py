def test_worker_seed_preamble_refresh_tracks_the_worker_preamble(tmp_path) -> None:
    """The worker-facing seed must not drift from the session's preamble.

    `<worker_repo>/isabelle/` is written once at setup; nothing refreshed it, so
    an edit to `Tablet/Preamble.thy` reached the checker's session dir but not
    the worker, which then compiled against a narrower import root than the gate
    used — the live system_feedback that surfaced this.
    """
    from trellis.checker.isabelle_scaffold import (
        DERIVED_PREAMBLE_MARKER,
        generate_preamble_thy,
        refresh_worker_seed_preamble,
    )

    (tmp_path / "Tablet").mkdir(parents=True)
    (tmp_path / "Tablet" / "Preamble.thy").write_text(
        'theory Tablet_Preamble\n  imports "HOL-Probability.Probability"\nbegin\n\nend\n',
        encoding="utf-8",
    )
    seed = tmp_path / "isabelle"
    seed.mkdir()
    stale = generate_preamble_thy(None)  # the setup-time constant
    (seed / "Tablet_Preamble.thy").write_text(stale, encoding="utf-8")
    (seed / "ROOT").write_text("session Tablet_Base in \"base\" = \"HOL-Probability\" +\n", encoding="utf-8")
    root_before = (seed / "ROOT").read_bytes()

    got = refresh_worker_seed_preamble(tmp_path)

    body = (seed / "Tablet_Preamble.thy").read_text(encoding="utf-8")
    assert got == ["HOL-Probability.Probability"]
    assert "HOL-Probability.Probability" in body
    assert DERIVED_PREAMBLE_MARKER in body
    # The seed's ROOT is node-less by design — the refresh must not touch it.
    assert (seed / "ROOT").read_bytes() == root_before
    # Idempotent.
    before = (seed / "Tablet_Preamble.thy").read_bytes()
    refresh_worker_seed_preamble(tmp_path)
    assert (seed / "Tablet_Preamble.thy").read_bytes() == before
