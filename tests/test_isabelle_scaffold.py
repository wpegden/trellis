def test_sync_session_writes_root_and_preamble(tmp_path: Path) -> None:
    """End-to-end: two worker node theories present on disk ⇒ ROOT lists both
    (sorted) + Preamble, and the worker bodies are left UNTOUCHED."""
    session_dir = tmp_path / "isabelle"
    session_dir.mkdir()
    # Worker-authored complete node theories (the Tablet/<Node>.lean analogue).
    alpha_body = (
        "theory Tablet_Alpha\n  imports Tablet_Preamble\nbegin\n\n"
        'lemma Alpha: "(1::nat)+1=2" by simp\n\nend\n'
    )
    beta_body = (
        "theory Tablet_Beta\n  imports Tablet_Preamble Tablet_Alpha\nbegin\n\n"
        'lemma Beta: "(2::nat)+0=2" by simp\n\nend\n'
    )
    (session_dir / "Tablet_Alpha.thy").write_text(alpha_body, encoding="utf-8")
    (session_dir / "Tablet_Beta.thy").write_text(beta_body, encoding="utf-8")

    summary = scaffold.sync_session(session_dir)

    assert (session_dir / "ROOT").read_text(encoding="utf-8") == GOLDEN_ROOT_TWO_NODE
    assert (session_dir / "Tablet_Preamble.thy").read_text(
        encoding="utf-8"
    ) == GOLDEN_PREAMBLE
    # Worker bodies are NOT rewritten by the generator.
    assert (session_dir / "Tablet_Alpha.thy").read_text(encoding="utf-8") == alpha_body
    assert (session_dir / "Tablet_Beta.thy").read_text(encoding="utf-8") == beta_body
    assert summary["node_theories"] == ["Tablet_Alpha", "Tablet_Beta"]


