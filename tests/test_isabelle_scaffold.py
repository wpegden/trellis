# ============================ pure render goldens ============================

# The golden ROOT for a 2-node tablet {Alpha, Beta} (+ the always-present
# Tablet_Preamble base). Pinned byte-for-byte: the session-qualified names,
# the options block (quick_and_dirty=false, bounded threads/parallel_proofs/
# timeout, NO proofs=1), Preamble listed first, nodes sorted.
GOLDEN_ROOT_TWO_NODE = """\
(* Auto-generated by .trellis. Do not edit. *)
session Tablet_Base in "base" = "HOL-Probability" +
  options [record_proofs = 0, threads = 2, parallel_proofs = 1, timeout = 1800]

session Tablet = Tablet_Base +
  options [record_proofs = 0, threads = 2, parallel_proofs = 1, timeout = 1800]
  theories
    Tablet_Preamble
    Tablet_Alpha
    Tablet_Beta
"""

GOLDEN_PREAMBLE = """\
theory Tablet_Preamble
  imports Complex_Main
begin

end
"""


def test_golden_root_two_node() -> None:
    text = scaffold.generate_root(["Tablet_Alpha", "Tablet_Beta"])
    assert text == GOLDEN_ROOT_TWO_NODE


def test_golden_preamble() -> None:
    assert scaffold.generate_preamble_thy() == GOLDEN_PREAMBLE


def test_root_options_quick_and_dirty_false_and_no_proofs_option() -> None:
    """The soundness-relevant ROOT policy: quick_and_dirty=false (a stray
    sorry FAILS the build), ``record_proofs = 0`` for oracle attribution, and NO ``proofs`` option
    (invalid in 2025-2; oracle names record at level 0 regardless)."""
    text = scaffold.generate_root(["Tablet_Alpha"])
    # `quick_and_dirty` is deliberately NOT pinned in ROOT. Session options
    # OVERRIDE a command-line `-o`, so pinning it made the policy un-selectable
    # per invocation — and pinning it FALSE made a single open node fail the
    # whole-session materialization build, contradicting the phase contract that
    # a node may be OPEN with its proof deferred. Isabelle's global default is
    # already `false`, so STRICT remains the default; materialization opts into
    # `quick_and_dirty=true` explicitly and the completion gate keeps the default.
    assert "quick_and_dirty" not in text
    # The stale option is a BARE ``proofs`` key; ``parallel_proofs`` is a
    # different, valid option, so match the bare key with a leading delimiter.
    assert "[proofs = " not in text and ", proofs = " not in text
    # `record_proofs = 0` is REQUIRED (it used to be wrongly excluded). Level 0
    # retains the theorem dependency boxes and oracle names the checker's cut
    # traversal needs to attribute an oracle to the proof that introduced it —
    # i.e. to tell a node's own `sorry` apart from a declared child's. It does
    # NOT record explicit proof terms (level 2), which would be costly and would
    # not reuse the prebuilt HOL heap. `proofs = 1` really is not a valid option
    # name; `record_proofs` is (`etc/options`).
    assert "record_proofs = 0" in text
    # The working session parents on the warm base; the base parents on
    # HOL-Probability. Both stanzas land in the one ROOT. The hyphenated parent
    # MUST be double-quoted (it is not a bare long-ident, so an unquoted
    # ``= HOL-Probability +`` fails the ROOT parse), and the base stanza MUST
    # carry an ``in "<subdir>"`` so it does not share the ROOT dir with
    # ``Tablet`` (``Duplicate use of directory`` otherwise).
    assert "session Tablet = Tablet_Base +" in text
    assert 'session Tablet_Base in "base" = "HOL-Probability" +' in text
    # The bare unquoted form (the pre-fix bug) must NOT appear.
    assert "= HOL-Probability +" not in text


