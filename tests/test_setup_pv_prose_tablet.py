def test_prose_goal_parse_failures_are_loud_and_precede_extraction() -> None:
    cases = [
        (
            b"# Goal\n\nThis file has no target section.\n",
            "declares no targets",
        ),
        (
            b"# Goal\n\n### `target` trailing words\n",
            "malformed target heading",
        ),
        (
            b"# Goal\n\n### `target`\n\n### `target`\n",
            "repeats target heading",
        ),
        (
            b"# Goal\n\n### `target`\n\n### `target_more`\n",
            "prefix-ambiguous targets",
        ),
        (
            b"# Goal\n\n### `target`\n\xff\n",
            "is not valid UTF-8",
        ),
        (
            b"# Goal\n\n```markdown\n### `not_a_real_heading`\n```\n",
            "declares no targets",
        ),
    ]
    with tempfile.TemporaryDirectory(prefix=".prose-goal-error-test-", dir=ROOT) as raw:
        scratch = Path(raw)
        crate = scratch / "crate"
        (crate / "src").mkdir(parents=True)
        (crate / "Cargo.toml").write_text(
            '[package]\nname = "fixture"\nversion = "0.1.0"\nedition = "2021"\n',
            encoding="utf-8",
        )
        (crate / "src/lib.rs").write_text(
            "pub fn target() -> u64 { 0 }\n", encoding="utf-8"
        )

        for index, (goal_bytes, expected) in enumerate(cases):
            goal = scratch / f"bad-goal-{index}.md"
            goal.write_bytes(goal_bytes)
            out_repo = scratch / f"out-{index}"
            completed = subprocess.run(
                [
                    str(ROOT / "scripts/setup_pv_repo.sh"),
                    "--crate",
                    str(crate),
                    "--out-repo",
                    str(out_repo),
                    "--goal",
                    str(goal),
                ],
                cwd=ROOT,
                text=True,
                capture_output=True,
                check=False,
            )
            assert completed.returncode != 0
            assert expected in completed.stderr, completed.stderr
            assert not out_repo.exists(), "goal validation must fail before extraction"
