def _disk_node_stems(tablet: Path) -> set[str]:
    return {
        path.stem
        for path in tablet.iterdir()
        # The kernel materializes shared TeX macros, not an authored node.
        if path.is_file() and path.suffix in {".lean", ".tex"} and path.name != "header.tex"
    }


def _make_corpus_repo(
    root: Path, name: str, files: dict[str, str]
) -> tuple[Path, str]:
    repo = root / name
    for relative, contents in files.items():
        path = repo / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(contents, encoding="utf-8")
    subprocess.run(["git", "init", "-q", str(repo)], check=True)
    subprocess.run(["git", "-C", str(repo), "add", "-A"], check=True)
    subprocess.run(
        [
            "git",
            "-C",
            str(repo),
            "-c",
            "user.name=PV corpus fixture",
            "-c",
            "user.email=pv-corpus-fixture@example.invalid",
            "commit",
            "-q",
            "-m",
            "fixture corpus pin",
        ],
        check=True,
    )
    rev = subprocess.run(
        ["git", "-C", str(repo), "rev-parse", "HEAD"],
        check=True,
        text=True,
        capture_output=True,
    ).stdout.strip()
    return repo, rev


def test_prose_goal_parser_tracks_rendered_commonmark_headings(tmp_path: Path) -> None:
    cases = [
        (
            b"# Goal\n\n   ### `indented`\n",
            [{"name": "indented", "resolution": "decide", "line": 3}],
        ),
        (
            b"# Goal\n\n```\n```rust\n### `quoted_code`\n```\n"
            b"### `after_fence`\n",
            [{"name": "after_fence", "resolution": "decide", "line": 7}],
        ),
        (
            b"# Goal\n\n<!--\n### `commented_out`\n-->\n"
            b"### `visible` <!-- rendered comment --> ###\n",
            [{"name": "visible", "resolution": "decide", "line": 6}],
        ),
    ]
    for index, (contents, expected) in enumerate(cases):
        goal = tmp_path / f"goal-{index}.md"
        goal.write_bytes(contents)
        assert parse_goal(goal)["targets"] == expected


def test_fresh_prose_tablet_contains_only_extraction_seed_nodes() -> None:
    # Keep the setup script's explicitly configured Cargo target and all other
    # scratch paths inside the clone, matching the production safety contract.
    with tempfile.TemporaryDirectory(prefix=".prose-seed-test-", dir=ROOT) as raw:
        scratch = Path(raw)
        crate = scratch / "crate"
        (crate / "src").mkdir(parents=True)
        (crate / "Cargo.toml").write_text(
            '[package]\nname = "fixture"\nversion = "0.1.0"\nedition = "2021"\n',
            encoding="utf-8",
        )
        (crate / "src" / "lib.rs").write_text(
            "pub fn f_model() -> u64 { 0 }\n", encoding="utf-8"
        )
        (crate / "build.rs").write_text("fn main() {}\n", encoding="utf-8")
        (crate / "source-data").mkdir()
        (crate / "source-data/value.txt").write_text("adapted\n", encoding="utf-8")
        unadapted_crate = scratch / "unadapted-crate"
        shutil.copytree(crate, unadapted_crate)
        (unadapted_crate / "src" / "lib.rs").write_text(
            "pub fn f_model() -> u64 { 1 }\n", encoding="utf-8"
        )
        goal = scratch / "authored-goal.md"
        goal_bytes = (
            b"# Goal\r\n\r\n## Obligations\r\n\r\n### `f_model`\r\n\r\n"
            b"Prove the result is the intended caf\xc3\xa9 value.\r\n"
        )
        goal.write_bytes(goal_bytes)

        reference_repo, reference_rev = _make_corpus_repo(
            scratch, "reference-upstream", {"src/reference.md": "reference\n"}
        )
        reference_tag = "fixture-floating-tag"
        subprocess.run(
            ["git", "-C", str(reference_repo), "tag", reference_tag], check=True
        )
        nomicon_repo, nomicon_rev = _make_corpus_repo(
            scratch, "nomicon-upstream", {"src/nomicon.md": "nomicon\n"}
        )
        rust_repo, rust_rev = _make_corpus_repo(
            scratch,
            "rust-upstream",
            {
                "library/core/src/slice/mod.rs": "pub fn first() {}\n",
                "library/std/src/lib.rs": "//! std fixture\n",
                "compiler/should-not-be-checked-out.txt": "large unrelated tree\n",
            },
        )

        fake_bin = scratch / "bin"
        charon, aeneas = _fake_host_tools(fake_bin)
        aeneas_lib = scratch / "aeneas-lean"
        aeneas_lib.mkdir()
        out_repo = scratch / "tablet-repo"
        runtime_root = scratch / "runtime"
        cargo_target = scratch / "cargo-target"
        work_root = scratch / "work"

        env = os.environ.copy()
        env["PATH"] = f"{fake_bin}:{env['PATH']}"
        env["PV_PREWARM_PATH"] = f"{fake_bin}:/usr/bin:/bin"
        env["RUST_REFERENCE_GIT_URL"] = str(reference_repo)
        env["RUST_REFERENCE_REV"] = reference_tag
        env["NOMICON_GIT_URL"] = str(nomicon_repo)
        env["NOMICON_REV"] = nomicon_rev
        env["RUST_STD_GIT_URL"] = str(rust_repo)
        env["RUST_STD_REV"] = rust_rev
        completed = subprocess.run(
            [
                str(ROOT / "scripts" / "setup_pv_repo.sh"),
                "--crate",
                str(crate),
                "--unadapted-crate",
                str(unadapted_crate),
                "--out-repo",
                str(out_repo),
                "--runtime-root",
                str(runtime_root),
                "--goal",
                str(goal),
                "--charon-bin",
                str(charon),
                "--aeneas-bin",
                str(aeneas),
                "--aeneas-lean-lib",
                str(aeneas_lib),
                "--cargo-target-dir",
                str(cargo_target),
                "--work-root",
                str(work_root),
            ],
            cwd=ROOT,
            env=env,
            text=True,
            capture_output=True,
            check=False,
        )
        assert completed.returncode == 0, (
            f"setup failed with {completed.returncode}\n"
            f"stdout:\n{completed.stdout}\nstderr:\n{completed.stderr}"
        )

        pv = json.loads((out_repo / "pv_tablet.json").read_text(encoding="utf-8"))
        assert pv["verification_targets"] == [
            {"name": "f_model", "resolution": "decide"}
        ]
        assert pv["extraction_toolchain"]["rustc_vv"].startswith("rustc ")
        assert pv["extraction_toolchain"]["target_triple"]
        assert pv["extraction_toolchain"]["extraction_profile"] == "dev"
        expected_toolchain_hashes = {
            model["provenance"]["extractor_toolchain_sha256"]
            for model in pv["extraction_models"]
        }
        assert expected_toolchain_hashes == {
            hashlib.sha256(
                json.dumps(
                    {
                        "extraction_toolchain": pv["extraction_toolchain"],
                        "extractor_stack": sorted(pv["extractor_stack"]),
                    },
                    ensure_ascii=False,
                    allow_nan=False,
                    sort_keys=True,
                    separators=(",", ":"),
                ).encode("utf-8")
            ).hexdigest()
        }
        for model in pv["extraction_models"]:
            provenance = model["provenance"]
            assert provenance["problem_id"] == "fixture"
            assert provenance["source_file"] == "src/lib.rs"
            assert provenance["source_sha256"]
            assert provenance["extractor_toolchain_sha256"]
            assert not any(value == "" for value in provenance.values())
        tcb = json.loads(
            (out_repo / "tcb_manifest.json").read_text(encoding="utf-8")
        )
        extraction_provenance = tcb["extraction_provenance"]
        assert extraction_provenance["extraction_toolchain"] == pv["extraction_toolchain"]
        assert extraction_provenance["extractor_toolchain_sha256"] in expected_toolchain_hashes
        assert extraction_provenance["source_digests"]
        assert all(
            entry.get("field") and entry.get("reason")
            for entry in extraction_provenance["not_recorded"]
        )
        assert (out_repo / "GOAL.md").read_bytes() == goal_bytes
        config = json.loads(
            (out_repo / "trellis.config.json").read_text(encoding="utf-8")
        )
        assert config["goal_file"] == "GOAL.md"
        assert config["pv_tablet"]["verification_targets"] == [
            {"name": "f_model", "resolution": "decide"}
        ]
        assert (out_repo / "crate/src/lib.rs").read_bytes() == (
            crate / "src/lib.rs"
        ).read_bytes()
        assert (out_repo / "crate/build.rs").read_bytes() == (crate / "build.rs").read_bytes()
        assert (out_repo / "crate/source-data/value.txt").read_text() == "adapted\n"
        assert (out_repo / "unadapted-crate/src/lib.rs").read_bytes() == (
            unadapted_crate / "src/lib.rs"
        ).read_bytes()
        assert (out_repo / "crate/src/lib.rs").read_bytes() != (
            out_repo / "unadapted-crate/src/lib.rs"
        ).read_bytes()

        corpus = out_repo / "rust_docs_corpus"
        manifest = json.loads(
            (corpus / "CORPUS_MANIFEST.json").read_text(encoding="utf-8")
        )
        sources = {entry["name"]: entry for entry in manifest["sources"]}
        assert sources["rust-reference"] == {
            "name": "rust-reference",
            "url": str(reference_repo),
            "rev": reference_rev,
            "path": "rust-reference/src",
        }
        assert sources["rust-std"] == {
            "name": "rust-std",
            "url": str(rust_repo),
            "rev": rust_rev,
            "path": "rust-std/library",
        }
        assert (corpus / "rust-std/library/core/src/slice/mod.rs").is_file()
        assert not (corpus / "rust-std/compiler").exists()
        assert not (corpus / "rust-reference/sentinel").exists()

        extraction_nodes = {entry["node"] for entry in pv["extraction_models"]}
        tablet = out_repo / "Tablet"
        assert (tablet / "header.tex").is_file()
        disk_nodes = _disk_node_stems(tablet)

        generated_role_nodes = {
            f"{model}_{role}" for model in extraction_nodes for role in ROLE_SUFFIXES
        }
        assert disk_nodes.isdisjoint(generated_role_nodes), (
            "prose setup must leave goal/support authoring to the worker; "
            f"found generated role nodes: {sorted(disk_nodes & generated_role_nodes)}"
        )
        assert disk_nodes - {"Assumptions"} == {"Preamble", *extraction_nodes}

        assumptions = (tablet / "Assumptions.lean").read_text(encoding="utf-8")
        assumption_code_lines = [
            line.lstrip()
            for line in assumptions.splitlines()
            if not line.lstrip().startswith("--")
        ]
        assert not any(line.startswith("def ") for line in assumption_code_lines)
        assert not any(line.startswith("axiom ") for line in assumption_code_lines)
        assert not any(line.startswith("opaque ") for line in assumption_code_lines)
        assert "-- BEGIN UNDERMODEL ASSUMPTION <id>" in assumptions
        assert "-- END UNDERMODEL ASSUMPTION <id>" in assumptions
        for node in extraction_nodes:
            extracted = (tablet / f"{node}.lean").read_text(encoding="utf-8")
            assert "import Tablet.Assumptions" not in extracted

        tablet_root = out_repo / "Tablet.lean"
        root_text = tablet_root.read_text(encoding="utf-8") if tablet_root.exists() else ""
        for node in generated_role_nodes:
            assert f"import Tablet.{node}" not in root_text

        # The fixture setup creates an internal git repo; removing it explicitly
        # avoids shutil traversing its read-only object permissions on some hosts.
        shutil.rmtree(out_repo / ".git", ignore_errors=True)


