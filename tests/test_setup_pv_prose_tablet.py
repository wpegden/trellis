    assert release.count('"scripts/pv_phase0.py"') >= 2
    assert release.count('"scripts/pv_source_adaptation_sandbox.py"') >= 2
    assert release.count('"scripts/pv_goal_binding.py"') >= 2
    assert '"kernel/tests/fixtures/pv_generic_source/"' in release
    assert "generate_pv_assessment_harness" not in release
    assert "pv_assessment_runtime" not in release


