from __future__ import annotations

from pathlib import Path

from scripts.pv_model_opacity import (
    GENERATED_LEAN_NAME,
    declared_names,
    read_model_bodiless_declarations,
    referenced_names,
    scan_bodiless_declarations,
)


MODEL = """-- THIS FILE WAS AUTOMATICALLY GENERATED BY THE BACKEND
import Aeneas
open Aeneas Aeneas.Std Result

namespace fixture

/-- [fixture::f]:
    Source: 'src/lib.rs', lines 1:0-1:32 -/
def f (x : Std.U64) : Result Std.U64 := do
  ok x

/-- [core::slice::{Slice}::first]:
    Source: '/core/slice.rs' -/
axiom core.slice.Slice.first {T : Type} : Slice T -> Result (Option T)

/-- [fixture::helper]:
    Source: 'src/lib.rs', lines 5:0-9:1 -/
axiom
  fixture.helper
  (x : Std.U64) : Result Std.U64

/-- [fixture::table]: -/
opaque fixture.table : Std.U64

/-- [fixture::axiom_free_check]: -/
def axiom_free_check : Nat := 1

/-- [fixture::the_axiom_of_choice]: -/
theorem the_axiom_of_choice : True := trivial

-- axiom commented.out
/- axiom block.commented.out -/

/-- [fixture::caller]:
    Source: 'src/lib.rs', lines 12:0-15:1 -/
def caller (x : Std.U64) : Result Std.U64 := do
  let y <- fixture.helper x
  -- core.slice.Slice.first is only named in this comment
  ok y

end fixture
"""


def _write_model(root: Path, text: str | bytes) -> Path:
    root.mkdir(parents=True, exist_ok=True)
    path = root / GENERATED_LEAN_NAME
    if isinstance(text, bytes):
        path.write_bytes(text)
    else:
        path.write_text(text, encoding="utf-8")
    return path


def test_only_the_bodiless_heads_are_reported_with_their_source_items() -> None:
    found = scan_bodiless_declarations(MODEL)
    assert found == [
        {
            "name": "core.slice.Slice.first",
            "kind": "axiom",
            "item_path": "core::slice::{Slice}::first",
        },
        {
            "name": "fixture.helper",
            "kind": "axiom",
            "item_path": "fixture::helper",
        },
        {"name": "fixture.table", "kind": "opaque", "item_path": "fixture::table"},
    ]
    # A declaration whose NAME merely carries the word, a commented-out head,
    # and every body-bearing declaration stay out of the list.
    names = {row["name"] for row in found}
    assert "axiom_free_check" not in names
    assert "the_axiom_of_choice" not in names
    assert "commented.out" not in names
    assert "block.commented.out" not in names


def test_reflowed_head_and_repeat_heads_are_read_once_each() -> None:
    text = "axiom\n  a.b.c\n  (T : Type) : Nat\n\naxiom a.b.c : Nat\nopaque a.b.c : Nat\n"
    assert scan_bodiless_declarations(text) == [
        {"name": "a.b.c", "kind": "axiom", "item_path": ""},
        {"name": "a.b.c", "kind": "opaque", "item_path": ""},
    ]


def test_direct_references_are_one_hop_and_ignore_comments() -> None:
    node = """/-- [fixture::caller]: -/
def caller (x : Std.U64) : Result Std.U64 := do
  let y <- fixture.helper x
  -- core.slice.Slice.first y
  ok y
"""
    names = {"fixture.helper", "fixture.table", "core.slice.Slice.first"}
    assert referenced_names(node, names) == ["fixture.helper"]
    assert declared_names(node, names) == []
    assert declared_names("axiom fixture.helper : Nat\n", names) == ["fixture.helper"]
    # A longer name that merely contains a bodiless name is not a reference.
    assert referenced_names("def q := fixture.helperish\n", names) == []


def test_read_model_names_the_generated_lean_it_read(tmp_path: Path) -> None:
    root = tmp_path / "extracted"
    _write_model(root, MODEL)
    # The serialized backend form sits alongside and is not what is read.
    (root / "m.llbc").write_bytes(b"\x00\x01llbc-not-lean\x00")
    scan = read_model_bodiless_declarations(root)
    assert scan["status"] == "read"
    assert scan["read_from"] == GENERATED_LEAN_NAME
    assert scan["detail"] == ""
    assert [row["name"] for row in scan["declarations"]] == [
        "core.slice.Slice.first",
        "fixture.helper",
        "fixture.table",
    ]


def test_a_clean_model_reads_as_an_empty_list_not_as_unread(tmp_path: Path) -> None:
    root = tmp_path / "extracted"
    _write_model(root, "namespace fixture\ndef f : Nat := 1\nend fixture\n")
    scan = read_model_bodiless_declarations(root)
    assert scan["status"] == "read"
    assert scan["declarations"] == []


def test_a_model_that_cannot_be_read_is_unread_not_clean(tmp_path: Path) -> None:
    root = tmp_path / "extracted"
    _write_model(root, b"axiom fixture.hidden : \xff\xfe not utf-8\n")
    scan = read_model_bodiless_declarations(root)
    assert scan["status"] == "unavailable"
    assert scan["declarations"] == []
    assert "cannot read the generated Lean" in scan["detail"]

    missing = read_model_bodiless_declarations(tmp_path / "absent")
    assert missing["status"] == "unavailable"
    assert missing["declarations"] == []


def test_a_file_that_is_not_lean_at_all_yields_nothing_without_raising() -> None:
    assert scan_bodiless_declarations("") == []
    assert scan_bodiless_declarations("/- unterminated axiom fixture.hidden") == []
    assert scan_bodiless_declarations("\x00\x01\x02 not a model") == []
